//
//  SetupOutput.swift
//  FleetHubSetup
//
//  Turns a domain's settings into the three things an admin can hand to
//  Jamf Pro: a configuration profile (.mobileconfig), a property list for
//  "Application & Custom Settings → Upload", or FleetHub's JSON schema for
//  the "External Applications → Custom Schema" form.
//
//  Nothing here ever receives a secret: generation reads only the domain
//  dictionaries from `SetupModel`.
//

import Foundation
import CryptoKit
import AppKit
import UniformTypeIdentifiers

enum SetupOutputFormat: String, CaseIterable, Identifiable {
    case profile, plist, schema
    var id: String { rawValue }

    var title: String {
        switch self {
        case .profile: "Configuration Profile"
        case .plist: "Property List"
        case .schema: "JSON Schema"
        }
    }

    var fileExtension: String {
        switch self {
        case .profile: "mobileconfig"
        case .plist: "plist"
        case .schema: "json"
        }
    }
}

enum SetupOutputError: LocalizedError {
    case schemaMissing(String)
    case encoding

    var errorDescription: String? {
        switch self {
        case .schemaMissing(let name): "The bundled file \(name) is missing from this copy of FleetHub Setup."
        case .encoding: "The settings could not be written as a property list."
        }
    }
}

@MainActor
enum SetupOutput {

    /// A UUID that is the same every time for the same tenant and name, so
    /// re-exporting or re-uploading a profile updates it in place instead of
    /// looking like a new profile to the Mac.
    static func stableUUID(_ name: String, tenant: String) -> String {
        let digest = SHA256.hash(data: Data("fleethub-setup|\(tenant.lowercased())|\(name)".utf8))
        var bytes = Array(digest.prefix(16))
        bytes[6] = (bytes[6] & 0x0F) | 0x50   // version 5 (name-based)
        bytes[8] = (bytes[8] & 0x3F) | 0x80   // RFC 4122 variant
        let hex = bytes.map { String(format: "%02X", $0) }.joined()
        let parts = [hex.prefix(8), hex.dropFirst(8).prefix(4), hex.dropFirst(12).prefix(4),
                     hex.dropFirst(16).prefix(4), hex.dropFirst(20)]
        return parts.map(String.init).joined(separator: "-")
    }

    static func plistData(_ dictionary: [String: Any]) throws -> Data {
        do {
            return try PropertyListSerialization.data(fromPropertyList: dictionary, format: .xml, options: 0)
        } catch {
            throw SetupOutputError.encoding
        }
    }

    /// The domain's settings as a bare property list.
    static func plist(for domain: SetupDomain, model: SetupModel) throws -> Data {
        try plistData(model.dictionary(for: domain))
    }

    /// One configuration profile carrying the given domains, each as its own
    /// managed-preferences payload.
    static func profile(for domains: [SetupDomain], model: SetupModel) throws -> Data {
        let tenant = model.normalizedJamfURL
        let organization = model.companyName.trimmingCharacters(in: .whitespaces)
        let payloads: [[String: Any]] = domains.map { domain in
            var payload = model.dictionary(for: domain)
            payload["PayloadType"] = domain.preferenceDomain
            payload["PayloadIdentifier"] = "\(domain.preferenceDomain).config"
            payload["PayloadUUID"] = stableUUID("payload.\(domain.rawValue)", tenant: tenant)
            payload["PayloadDisplayName"] = domain.profileName
            payload["PayloadVersion"] = 1
            payload["PayloadEnabled"] = true
            return payload
        }
        let single = domains.count == 1 ? domains[0] : nil
        let suffix = single?.rawValue ?? "all"
        var profile: [String: Any] = [
            "PayloadContent": payloads,
            "PayloadDisplayName": single?.profileName ?? "FleetHub — Settings",
            "PayloadDescription": "FleetHub settings generated by FleetHub Setup. Contains no secrets.",
            "PayloadIdentifier": "com.herojoneslabs.fleethub.profile.\(suffix)",
            "PayloadType": "Configuration",
            "PayloadUUID": stableUUID("profile.\(suffix)", tenant: tenant),
            "PayloadVersion": 1,
            "PayloadScope": "System"
        ]
        if !organization.isEmpty { profile["PayloadOrganization"] = organization }
        return try plistData(profile)
    }

    /// FleetHub's JSON schema for the domain, as shipped with Setup.
    static func schema(for domain: SetupDomain) throws -> Data {
        guard let url = Bundle.main.url(forResource: domain.schemaResource, withExtension: "json"),
              let data = try? Data(contentsOf: url) else {
            throw SetupOutputError.schemaMissing(domain.schemaResource + ".json")
        }
        return data
    }

    static func data(for domain: SetupDomain, format: SetupOutputFormat, model: SetupModel) throws -> Data {
        switch format {
        case .profile: try profile(for: [domain], model: model)
        case .plist: try plist(for: domain, model: model)
        case .schema: try schema(for: domain)
        }
    }

    // MARK: Private key encoding

    /// Tidies a PEM private key that was read from a file or pasted, and
    /// returns it in standard form: the BEGIN line, the key in 64-character
    /// lines, the END line. Returns nil when the text is not a PEM private
    /// key. Accepts both kinds Apple issues ("PRIVATE KEY" and "EC PRIVATE
    /// KEY") and forgives what pasting does to a key: lost line breaks,
    /// stray spaces, and the wrong number of dashes.
    nonisolated static func normalizedPrivateKeyPEM(_ text: String) -> String? {
        let pattern = #"-+\s*BEGIN ((?:[A-Z]+ )*PRIVATE KEY)\s*-+(.*?)-+\s*END \1\s*-+"#
        guard let regex = try? NSRegularExpression(pattern: pattern, options: [.dotMatchesLineSeparators]),
              let match = regex.firstMatch(in: text, range: NSRange(text.startIndex..., in: text)),
              let labelRange = Range(match.range(at: 1), in: text),
              let bodyRange = Range(match.range(at: 2), in: text) else { return nil }
        let label = String(text[labelRange])
        let body = text[bodyRange].filter { !$0.isWhitespace }
        // The body must itself be base64 of something key-sized.
        guard body.count >= 40, let decoded = Data(base64Encoded: String(body)), decoded.count >= 32 else { return nil }
        var lines = ["-----BEGIN \(label)-----"]
        var rest = Substring(body)
        while !rest.isEmpty {
            lines.append(String(rest.prefix(64)))
            rest = rest.dropFirst(64)
        }
        lines.append("-----END \(label)-----")
        return lines.joined(separator: "\n") + "\n"
    }

    /// The one-line form a Jamf script parameter can hold.
    nonisolated static func encodedPrivateKey(_ text: String) -> String? {
        normalizedPrivateKeyPEM(text).map { Data($0.utf8).base64EncodedString() }
    }

    // MARK: Credential import script

    static let credentialScriptName = "Import-FleetHub-Credentials"

    /// The Jamf policy script that hands API client secrets to FleetHub,
    /// exactly as shipped with Setup.
    static func credentialScript() throws -> String {
        guard let url = Bundle.main.url(forResource: credentialScriptName, withExtension: "sh"),
              let text = try? String(contentsOf: url, encoding: .utf8) else {
            throw SetupOutputError.schemaMissing(credentialScriptName + ".sh")
        }
        return text
    }

    static func fileName(for domain: SetupDomain, format: SetupOutputFormat) -> String {
        switch format {
        case .profile: "FleetHub-\(domain == .ui ? "UI" : domain.rawValue.capitalized).mobileconfig"
        case .plist: "\(domain.preferenceDomain).plist"
        case .schema: "\(domain.schemaResource).json"
        }
    }

    /// The domain's settings as indented `key   value` lines, for the
    /// on-screen preview.
    static func previewText(for domain: SetupDomain, model: SetupModel) -> String {
        var lines: [String] = []
        func scalar(_ value: Any) -> String {
            if let flag = value as? Bool { return flag ? "true" : "false" }
            if let text = value as? String { return text.isEmpty ? "\"\"" : text }
            return "\(value)"
        }
        func walk(_ dictionary: [String: Any], indent: Int) {
            let pad = String(repeating: "  ", count: indent)
            // Scalars first, then nested groups, each alphabetically.
            let keys = dictionary.keys.sorted {
                let leftNested = dictionary[$0] is [String: Any] || dictionary[$0] is [Any]
                let rightNested = dictionary[$1] is [String: Any] || dictionary[$1] is [Any]
                return leftNested == rightNested ? $0 < $1 : !leftNested
            }
            for key in keys {
                let value = dictionary[key]!
                if let nested = value as? [String: Any] {
                    lines.append(pad + key)
                    walk(nested, indent: indent + 1)
                } else if let list = value as? [[String: Any]] {
                    lines.append(pad + key)
                    for (index, item) in list.enumerated() {
                        lines.append(pad + "  [\(index + 1)]")
                        walk(item, indent: indent + 2)
                    }
                } else if let list = value as? [Any] {
                    lines.append(pad + key.padding(toLength: max(18, key.count + 1), withPad: " ", startingAt: 0)
                                 + list.map(scalar).joined(separator: ", "))
                } else {
                    lines.append(pad + key.padding(toLength: max(18, key.count + 1), withPad: " ", startingAt: 0) + scalar(value))
                }
            }
        }
        walk(model.dictionary(for: domain), indent: 0)
        return lines.joined(separator: "\n")
    }

    // MARK: Saving

    /// Asks where to save one file. Returns the saved URL, or nil if cancelled.
    @discardableResult
    static func save(_ data: Data, suggestedName: String) throws -> URL? {
        let panel = NSSavePanel()
        panel.nameFieldStringValue = suggestedName
        panel.canCreateDirectories = true
        guard panel.runModal() == .OK, let url = panel.url else { return nil }
        try data.write(to: url, options: .atomic)
        return url
    }

    /// Asks for a folder and writes every domain in every format into it.
    @discardableResult
    static func saveEverything(model: SetupModel) throws -> URL? {
        let panel = NSOpenPanel()
        panel.canChooseDirectories = true
        panel.canChooseFiles = false
        panel.canCreateDirectories = true
        panel.prompt = "Export Here"
        panel.message = "Choose a folder for the FleetHub profiles, property lists and schemas."
        guard panel.runModal() == .OK, let folder = panel.url else { return nil }
        let target = folder.appendingPathComponent("FleetHub Settings", isDirectory: true)
        try FileManager.default.createDirectory(at: target, withIntermediateDirectories: true)
        for domain in SetupDomain.allCases {
            for format in SetupOutputFormat.allCases {
                let data = try data(for: domain, format: format, model: model)
                try data.write(to: target.appendingPathComponent(fileName(for: domain, format: format)), options: .atomic)
            }
        }
        let all = try profile(for: SetupDomain.allCases, model: model)
        try all.write(to: target.appendingPathComponent("FleetHub-All.mobileconfig"), options: .atomic)
        return target
    }
}
